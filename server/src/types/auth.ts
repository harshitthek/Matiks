/**
 * MATIKS HACKATHON ENGINE — PLUGGABLE AUTHENTICATION CONTRACTS (auth.ts)
 * 
 * Formal definitions for AuthUser identity, permission roles, and the IAuthProvider contract.
 * Enables zero-refactor switching between Phase 1 (Local Hackathon) and Phase 2 (Club OIDC).
 */

export type AuthRole = 'participant' | 'captain' | 'admin';

export interface AuthUser {
  id: string; // Unique student ID, Roll Number, or OIDC sub
  rollNumber: string; // Primary academic identifier or GitHub handle
  displayName: string;
  isClubMember: boolean; // Verified UFC / FOSS club member status
  teamCode?: string; // Associated team room
  role: AuthRole;
  is_admin?: boolean;
  isAdmin?: boolean;
  email?: string;
  githubUsername?: string;
  picture?: string;
  clubRole?: string;
}

export interface PlayerLoginCredentials {
  rollNumber: string;
  name: string;
  teamCode?: string;
}

export interface AdminLoginCredentials {
  passcode: string;
}

export interface AuthResult {
  user: AuthUser;
  token: string;
}

export interface IAuthProvider {
  readonly providerName: string;

  /**
   * Authenticates a student participant and issues an active session token.
   */
  loginPlayer(credentials: PlayerLoginCredentials): Promise<AuthResult>;

  /**
   * Authenticates a hackathon administrator against pre-shared secret or SSO.
   */
  loginAdmin(credentials: AdminLoginCredentials): Promise<AuthResult>;

  /**
   * Validates a session token and returns the authenticated user identity.
   */
  verifySession(token: string): Promise<AuthUser | null>;

  /**
   * Queries verified membership records to verify if student is an official club member.
   */
  validateClubMembership(identifier: string): Promise<boolean>;

  /**
   * Optional: Returns authorization URL for OAuth2 / OIDC code flow.
   */
  getAuthUrl?(state?: string, clientOrigin?: string): string;

  /**
   * Optional: Extracts and verifies client origin embedded in authenticated state.
   */
  extractOriginFromState?(state: string, now?: number): string | null;

  /**
   * Optional: Exchanges authorization code for access tokens and user profile.
   */
  exchangeCode?(code: string, state?: string): Promise<AuthResult>;

  /**
   * Optional: Validates that an OAuth2 / OIDC state was securely generated by this server.
   */
  validateState?(state: string): boolean;
}
